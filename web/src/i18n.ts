const DICTS: Record<Lang, Dict> = { ru, en };

/** Which of the three Russian forms a number takes.
 *
 *  Russian needs one / few / many, and picking the wrong one is the kind of
 *  thing that makes an interface read as unfinished: "1 аккаунтов" beside a
 *  perfectly correct "5 аккаунтов". English collapses to two forms, which the
 *  same three keys cover by repeating one of them.
 */
function pluralForm(n: number, lang: Lang): "one" | "few" | "many" {
  const abs = Math.abs(n);
  if (lang !== "ru") return abs === 1 ? "one" : "many";
  if (abs % 10 === 1 && abs % 100 !== 11) return "one";
  if (abs % 10 >= 2 && abs % 10 <= 4 && (abs % 100 < 10 || abs % 100 >= 20)) {
    return "few";
  }
  return "many";
}

export function makeT(lang: Lang) {
  const dict = DICTS[lang] ?? ru;

  function t(key: string, params?: Record<string, unknown>): string {
    let text = dict[key] ?? ru[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v ?? ""));
      }
    }
    return text;
  }

  /** "3 кампании" — the number and the word that agrees with it. */
  t.count = function count(n: number, key: string): string {
    return `${n} ${t(`${key}.${pluralForm(n, lang)}`)}`;
  };

  return t;
}

export type T = ReturnType<typeof makeT>;
