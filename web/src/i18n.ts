/** A message from the backend: a code, and what goes into its wording. */
export interface Msg {
  code: string;
  params?: Record<string, unknown>;
}

function isMsg(value: unknown): value is Msg {
  return typeof value === "object" && value !== null
    && typeof (value as Msg).code === "string";
}

/** Which of the three Russian forms a number takes: one / few / many.
 *  English collapses to two forms, which the same three keys cover. */
function pluralForm(n: number, lang: Lang): "one" | "few" | "many" {
  const abs = Math.abs(n);
  if (lang !== "ru") return abs === 1 ? "one" : "many";
  if (abs % 10 === 1 && abs % 100 !== 11) return "one";
  if (abs % 10 >= 2 && abs % 10 <= 4 && (abs % 100 < 10 || abs % 100 >= 20)) {
    return "few";
  }
  return "many";
}

export function makeT(lang: Lang) {
  const dict: Record<string, string> = lang === "en" ? en : ru;

  function fill(text: string, params?: Record<string, unknown>): string {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (_all, name: string) => {
      const value = params[name];
      if (isMsg(value)) return t.msg(value);
      return value === undefined || value === null ? "" : String(value);
    });
  }

  /** A key known when the code is written: checked by the compiler. */
  function t(key: Key, params?: Record<string, unknown>): string {
    return fill(dict[key], params);
  }

  /** A key put together at run time - a state, a media kind. */
  t.dyn = function dyn(key: string, params?: Record<string, unknown>): string {
    return fill(dict[key] ?? key, params);
  };

  /** A message from the backend. "raw" is text from outside the app,
   *  shown as it came. */
  t.msg = function translate(message: Msg | null | undefined): string {
    if (!message) return "";
    if (message.code === "raw") return String(message.params?.text ?? "");
    return t.dyn(message.code, message.params);
  };

  /** "3 кампании" — the number and the word that agrees with it. */
  t.count = function count(n: number, key: "count.campaigns" | "count.accounts"): string {
    return `${n} ${t(`${key}.${pluralForm(n, lang)}`)}`;
  };

  return t;
}

export type T = ReturnType<typeof makeT>;
